-- ─── the agentic spine ────────────────────────────────────────────────────

-- Every proposal writes a row here BEFORE approval, so the audit trail records
-- what was suggested even when the owner says no. Powers FR-D8 and is what the
-- trajectory evals assert against.
create table if not exists agent_actions (
  id            bigint primary key generated by default as identity,
  restaurant_id uuid not null references restaurants(id) on delete cascade,
  agent         text not null,                       -- 'Anumaan Agent', etc.
  tool_name     text,                                -- null for notify-only
  tool_args     jsonb,
  proposal      text not null,                       -- plain language, for the log
  basis         text not null,                       -- why — never optional
  status        agent_action_status not null default 'proposed',
  result_ref    text,                                -- what changed, if anything
  created_at    timestamptz not null default now(),
  resolved_at   timestamptz,
  resolved_by   uuid references auth.users(id) on delete set null
);
create index if not exists agent_actions_log_idx
  on agent_actions (restaurant_id, created_at desc);

-- Tasks pushed to the Kitchen Board once a Prep & Forecast proposal is approved.
create table if not exists prep_tasks (
  id              bigint primary key generated by default as identity,
  restaurant_id   uuid not null references restaurants(id) on delete cascade,
  agent_action_id bigint references agent_actions(id) on delete set null,
  label           text not null,
  done            boolean not null default false,
  created_at      timestamptz not null default now()
);

-- ─── row-level security ───────────────────────────────────────────────────
-- The anon key ships to the browser, so RLS is the real boundary. Customers
-- are unauthenticated by design (FR-C1: no login to browse), which is why the
-- guest-facing tables are readable by anon and the owner-facing ones are not.
-- Route handlers add the role check on top; see lib/auth.ts (DET-003).

create or replace function current_role_is(target user_role)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from profiles
    where profiles.id = auth.uid() and profiles.role = target
  );
$$;

