-- Per-item daily history. This is what forecast.ts averages over — the
-- `is_synthetic` flag exists so the UI can say so out loud (PRD §10).
create table if not exists daily_summaries (
  id            bigint primary key generated by default as identity,
  restaurant_id uuid not null references restaurants(id) on delete cascade,
  menu_item_id  bigint not null references menu_items(id) on delete cascade,
  business_date date not null,
  qty_sold      int not null default 0,
  revenue       numeric(10, 2) not null default 0,
  is_synthetic  boolean not null default true,
  unique (restaurant_id, menu_item_id, business_date)
);
create index if not exists daily_summaries_lookup_idx
  on daily_summaries (restaurant_id, menu_item_id, business_date);

create table if not exists compliance_items (
  id            bigint primary key generated by default as identity,
  restaurant_id uuid not null references restaurants(id) on delete cascade,
  label         text not null,
  checked       boolean not null default false,
  checked_at    timestamptz,
  sort_order    int not null default 0
