-- ─── core ─────────────────────────────────────────────────────────────────

create table if not exists restaurants (
  id            uuid primary key default gen_random_uuid(),
  name          text not null,
  fssai_license text,
  upi_vpa       text,
  created_at    timestamptz not null default now()
);

-- Mirrors auth.users; `role` is the server-side source of truth for FR-A8.
create table if not exists profiles (
  id            uuid primary key references auth.users(id) on delete cascade,
  restaurant_id uuid references restaurants(id) on delete cascade,
  full_name     text,
  role          user_role not null default 'staff',
  created_at    timestamptz not null default now()
);

create table if not exists menu_items (
  id            bigint primary key generated by default as identity,
  restaurant_id uuid not null references restaurants(id) on delete cascade,
  name          text not null,
  category      text not null,
  veg           boolean not null default true,
  price         numeric(10, 2) not null check (price >= 0),
  available     boolean not null default true,
  description   text,
  created_at    timestamptz not null default now()
);
create index if not exists menu_items_restaurant_idx on menu_items (restaurant_id);

create table if not exists restaurant_tables (
  id            bigint primary key generated by default as identity,
  restaurant_id uuid not null references restaurants(id) on delete cascade,
  label         text not null,
  seats         int not null default 4,
  status        table_status not null default 'empty',
  updated_at    timestamptz not null default now(),
  unique (restaurant_id, label)
);

create table if not exists orders (
  id            bigint primary key generated by default as identity,
  restaurant_id uuid not null references restaurants(id) on delete cascade,
  code          text not null,                       -- human-facing id, e.g. 'O1'
  table_id      bigint references restaurant_tables(id) on delete set null,
  status        order_status not null default 'new',
  total         numeric(10, 2) not null default 0,
  paid          boolean not null default false,
  placed_at     timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  unique (restaurant_id, code)
);
create index if not exists orders_restaurant_status_idx on orders (restaurant_id, status);

create table if not exists order_items (
  id           bigint primary key generated by default as identity,
  order_id     bigint not null references orders(id) on delete cascade,
  menu_item_id bigint references menu_items(id) on delete set null,
  name         text not null,                        -- denormalised: the bill
  qty          int not null check (qty > 0),         -- must survive menu edits
  unit_price   numeric(10, 2) not null
);
create index if not exists order_items_order_idx on order_items (order_id);

create table if not exists queue_entries (
  id            bigint primary key generated by default as identity,
  restaurant_id uuid not null references restaurants(id) on delete cascade,
  name          text not null,
  party_size    int not null default 2,
  phone         text,
  status        queue_status not null default 'waiting',
  joined_at     timestamptz not null default now()
);

create table if not exists inventory_items (
  id            bigint primary key generated by default as identity,
  restaurant_id uuid not null references restaurants(id) on delete cascade,
  name          text not null,
  stock         numeric(10, 2) not null default 0,
  max_stock     numeric(10, 2) not null default 0,
  unit          text not null default 'kg',
  low_threshold numeric(10, 2) not null default 0,
  updated_at    timestamptz not null default now()
);

create table if not exists staff_members (
  id            bigint primary key generated by default as identity,
  restaurant_id uuid not null references restaurants(id) on delete cascade,
  name          text not null,
  role_label    text not null,
  shift         text
