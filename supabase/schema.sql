do $$
declare
  guest_readable text[] := array[
    'restaurants', 'menu_items', 'restaurant_tables', 'orders',
    'order_items', 'queue_entries'
  ];
  staff_writable text[] := array[
    'menu_items', 'restaurant_tables', 'orders', 'order_items',
    'queue_entries', 'inventory_items', 'compliance_items', 'prep_tasks'
  ];
  owner_only text[] := array[
    'inventory_items', 'staff_members', 'customers',
    'daily_summaries', 'compliance_items', 'agent_actions', 'prep_tasks'
  ];
  t text;
begin
  -- Guests browse the menu, place an order, and watch its status. Nothing else.
  foreach t in array guest_readable loop
    execute format('drop policy if exists guest_read on %I', t);
    execute format('create policy guest_read on %I for select using (true)', t);
  end loop;

  execute 'drop policy if exists guest_place_order on orders';
  execute 'create policy guest_place_order on orders for insert with check (true)';
  execute 'drop policy if exists guest_place_order_items on order_items';
  execute 'create policy guest_place_order_items on order_items for insert with check (true)';
  execute 'drop policy if exists guest_join_queue on queue_entries';
  execute 'create policy guest_join_queue on queue_entries for insert with check (true)';

  -- Signed-in staff run the floor.
  foreach t in array staff_writable loop
    execute format('drop policy if exists staff_write on %I', t);
    execute format(
      'create policy staff_write on %I for all to authenticated using (auth.uid() is not null) with check (auth.uid() is not null)', t
    );
  end loop;

  -- Owner-only surfaces — the DB half of FR-A8. The route handler enforces the
  -- same rule with a 403 so the failure is legible rather than an empty list.
  foreach t in array owner_only loop
    execute format('drop policy if exists owner_read on %I', t);
    execute format(
      'create policy owner_read on %I for select to authenticated using (current_role_is(''owner''))', t
    );
  end loop;
end $$;

drop policy if exists own_profile on profiles;
create policy own_profile on profiles
  for select to authenticated using (id = auth.uid());

-- New sign-ups land in profiles automatically; the first user of a restaurant
-- is promoted to owner by seed.sql or by hand.
create or replace function handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, full_name, role)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'full_name', new.email),
    coalesce((new.raw_user_meta_data ->> 'role')::user_role, 'staff')
  )
  on conflict (id) do nothing;
  return new;
end $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function handle_new_user();
